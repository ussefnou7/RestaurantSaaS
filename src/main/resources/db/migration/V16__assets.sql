-- RBAC: single ASSETS_MANAGE permission (all asset read/write endpoints guard on it).
INSERT INTO permissions (code, module, name, description, type)
VALUES
    ('ASSETS_MANAGE', 'ASSETS', 'Manage Assets',
     'View and manage fixed assets, lines, disposals, and maintenance.', 'ACTION')
ON CONFLICT (code) DO UPDATE
SET module = EXCLUDED.module,
    name = EXCLUDED.name,
    description = EXCLUDED.description,
    type = EXCLUDED.type,
    is_active = TRUE,
    updated_at = CURRENT_TIMESTAMP;

INSERT INTO role_permissions (role_id, permission_id, created_at)
SELECT r.id, p.id, CURRENT_TIMESTAMP
FROM roles r
JOIN permissions p ON p.code = 'ASSETS_MANAGE'
WHERE r.code IN ('OWNER', 'SYS_ADMIN')
ON CONFLICT (role_id, permission_id) DO NOTHING;
